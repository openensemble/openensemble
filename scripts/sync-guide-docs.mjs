// @ts-check
// Publish the in-app guide through the existing docs/ GitHub Pages source.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const guideDir = path.join(root, 'guide');
const outputDir = path.join(root, 'docs', 'guide');
const check = process.argv.includes('--check');
const marker = '<!-- Generated by scripts/sync-guide-docs.mjs';
const index = JSON.parse(fs.readFileSync(path.join(guideDir, 'index.json'), 'utf8'));
const pages = index.sections.flatMap(section => section.pages);
const slugs = new Set();
for (const page of pages) {
  if (!/^[a-z0-9-]+$/.test(page.slug) || page.slug === 'index' || slugs.has(page.slug)) {
    throw new Error('Invalid or duplicate guide slug: ' + page.slug);
  }
  slugs.add(page.slug);
}
const sourceSlugs = fs.readdirSync(guideDir).filter(name => name.endsWith('.md')).map(name => name.slice(0, -3));
for (const slug of sourceSlugs) {
  if (!slugs.has(slug)) throw new Error('Guide page is missing from guide/index.json: ' + slug);
}
const output = new Map();
let order = 0;
for (const page of pages) {
  const source = fs.readFileSync(path.join(guideDir, page.slug + '.md'), 'utf8');
  const body = source.replace(/\]\((?:\.\/)?([a-z0-9-]+)\.md(#[^)]*)?\)/g, (_, slug, anchor = '') => {
    if (!slugs.has(slug)) throw new Error(page.slug + ' links to an unindexed guide: ' + slug);
    return '](../' + slug + '/' + anchor + ')';
  });
  output.set(page.slug + '.md', [
    '---', 'title: ' + JSON.stringify(page.title), 'parent: User guide',
    'nav_order: ' + (++order), 'permalink: /guide/' + page.slug + '/', '---', '',
    marker + ' from guide/' + page.slug + '.md. Edit the source. -->',
    '{% raw %}', body.trimEnd(), '{% endraw %}', '',
  ].join('\n'));
}
const overview = ['---', 'title: User guide', 'nav_order: 3', 'has_children: true',
  'has_toc: false', 'permalink: /guide/', '---', '',
  marker + ' from guide/index.json. Edit the source. -->', '', '# User guide', '',
  'These pages use the same source as OpenEnsemble’s in-app Guide.', '',
  'New installation? Start with [installation](../getting-started), then',
  '[get your first reply](./getting-started/).', ''];
for (const section of index.sections) {
  overview.push('## ' + section.title, '');
  for (const page of section.pages) overview.push('- [' + page.title + '](./' + page.slug + '/)');
  overview.push('');
}
output.set('index.md', overview.join('\n'));
let changed = 0;
if (!check) fs.mkdirSync(outputDir, { recursive: true });
for (const [name, body] of output) {
  const dest = path.join(outputDir, name);
  const previous = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
  if (previous === body) continue;
  changed++;
  if (check) console.error('Guide website is out of date: docs/guide/' + name);
  else fs.writeFileSync(dest, body);
}
if (fs.existsSync(outputDir)) {
  for (const name of fs.readdirSync(outputDir)) {
    if (!name.endsWith('.md') || output.has(name)) continue;
    const dest = path.join(outputDir, name);
    if (!fs.readFileSync(dest, 'utf8').includes(marker)) continue;
    changed++;
    if (check) console.error('Stale generated guide page: docs/guide/' + name);
    else fs.unlinkSync(dest);
  }
}
if (check && changed) {
  console.error('Run node scripts/sync-guide-docs.mjs and include the generated pages.');
  process.exitCode = 1;
} else {
  console.log('Guide website: ' + pages.length + ' pages ' + (check ? 'match their sources.' : 'synchronized.'));
}
